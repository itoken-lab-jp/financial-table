/**
 * 左に残す表と数字の表の行の高さ（App.tsx の行の高さそろえ）。2 つの表の同じ行に同じ値を書く。
 * own は左右の高いほうの高さ（CSS px）。高さは CSS の整数 px に切り上げる（2026-10-24）。
 *
 * 2026-10-15 から 2.1.9.0 までは、表の上の端から数えた行の境を画面の画素の目（1 / (devicePixelRatio × 倍率)）に切り上げ、端数の高さ
 * （39.2px など）で書いていた。DOM の行の位置は左右で 0.04px 以内にそろうのに、Desktop では左に残す表（sticky）の横線が、数字の列より
 * 全行で 1 画素（実寸大）〜2 画素（ページに合わせる）下に描かれた。描くときの丸めが左右の表で違う。整数 px なら、Desktop の 125% で
 * 線がそろい、にじみも出なかった（診断版 2.1.9.902）
 */
export function rowHeightsOf(owns: number[]): number[] {
    return owns.map((own) => Math.max(0, Math.ceil(own - 0.01)));
}
